#!/usr/bin/env python3
"""Generate Flutter tokens and vector paths from Sunny Growth design sources."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/themes/sunny_growth'
OUTPUT = ROOT / 'lib/theme/sunny_growth_tokens.dart'


def generate():
    tokens = json.loads((SOURCE / 'tokens.json').read_text())

    def resolve(value):
        if isinstance(value, str) and value.startswith('{') and value.endswith('}'):
            node = tokens
            for part in value[1:-1].split('.'):
                node = node[part]
            return resolve(node['$value'])
        return value

    def color(value):
        value = resolve(value).removeprefix('#')
        if not re.fullmatch('[0-9a-fA-F]{6}', value):
            raise ValueError(f'Expected opaque RGB color: {value}')
        return f'Color(0xFF{value.upper()})'

    def emit(node, prefix=()):
        for name, entry in node.items():
            if name.startswith('$'):
                continue
            path = (*prefix, name)
            if '$value' not in entry:
                yield from emit(entry, path)
                continue
            identifier = path[0] + ''.join(p[0].upper() + p[1:] for p in path[1:])
            value = resolve(entry['$value'])
            kind = entry['$type']
            if kind == 'color':
                expression = color(value)
            elif kind == 'dimension':
                expression = str(float(value['value']))
            elif kind == 'number':
                expression = str(float(value))
            elif kind == 'typography':
                size = value['fontSize']
                features = ', fontFeatures: [FontFeature.tabularFigures()]' if value.get('tabular') else ''
                expression = (
                    f'TextStyle(fontSize: {size}, height: {value["lineHeight"] / size}, '
                    f'fontWeight: FontWeight.w{value["fontWeight"]}{features})'
                )
            else:
                raise ValueError(f'Unsupported token type: {kind}')
            yield f'  static const {identifier} = {expression};'

    svg = ET.parse(SOURCE / 'sun_cloud.svg').getroot()
    artwork = []
    for node in svg:
        if node.tag.rsplit('}', 1)[-1] != 'path':
            raise ValueError('Illustration must contain only flattened SVG paths')
        fill = 'null' if node.get('fill', 'none') == 'none' else color(node.get('fill'))
        stroke = 'null' if node.get('stroke', 'none') == 'none' else color(node.get('stroke'))
        artwork.append(
            f'    (path: {json.dumps(node.attrib["d"])}, fill: {fill}, '
            f'stroke: {stroke}, width: {float(node.get("stroke-width", 0))}),'
        )
    source = '\n'.join([
        '// GENERATED by tool/generate_sunny_growth.py. Do not edit.',
        '// Source: assets/themes/sunny_growth/{tokens.json,sun_cloud.svg}',
        "import 'package:flutter/material.dart';",
        '',
        'abstract final class SunnyGrowthTokens {',
        f'  static const version = {json.dumps(tokens["$version"])};',
        *emit(tokens['sys']),
        *emit(tokens['comp'], ('comp',)),
        '',
        '  static const sunCloudPaths = <({String path, Color? fill, Color? stroke, double width})>[',
        *artwork,
        '  ];',
        '}',
        '',
    ])
    return subprocess.run(
        ['dart', 'format', '--output=show', '--summary=none'],
        input=source, text=True, capture_output=True, check=True,
    ).stdout


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != source:
            raise SystemExit('Sunny Growth generated source is out of date.')
        print('Sunny Growth tokens and vector source are in sync.')
    else:
        OUTPUT.write_text(source)
        print(f'Generated {OUTPUT.relative_to(ROOT)}')
