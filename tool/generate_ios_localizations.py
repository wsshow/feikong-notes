"""Generate native share/reminder strings from the app's bilingual ARB files."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEYS = {
    "reminder.title": "iosReminderTitle",
    "reminder.body": "iosReminderBody",
    "share.title": "incomingShareTitle",
    "share.placeholder": "iosSharePlaceholder",
    "share.saved": "iosShareSaved",
    "share.openApp": "iosShareOpenApp",
    "share.done": "reminderConfirm",
    "share.full": "incomingShareQueueFull",
    "share.tooLarge": "incomingShareLimit",
    "share.failed": "incomingShareReadFailed",
    "share.failedTitle": "iosShareFailedTitle",
}
INFO_KEYS = {
    "CFBundleDisplayName": "iosAppDisplayName",
    "NSCameraUsageDescription": "iosCameraPurpose",
    "NSMicrophoneUsageDescription": "iosMicrophonePurpose",
    "NSPhotoLibraryUsageDescription": "iosPhotoLibraryPurpose",
    "NSFaceIDUsageDescription": "iosFaceIdPurpose",
    "NSLocationWhenInUseUsageDescription": "iosLocationPurpose",
    "NSLocalNetworkUsageDescription": "iosLocalNetworkPurpose",
}


def generate(check=False):
    for language, native in [("en", "en"), ("zh", "zh-Hans")]:
        arb = json.loads((ROOT / f"lib/l10n/app_{language}.arb").read_text())
        for filename, keys in [("Localizable.strings", KEYS), ("InfoPlist.strings", INFO_KEYS)]:
            output = "// Generated by tool/generate_ios_localizations.py.\n"
            output += "".join(f'{json.dumps(key)} = {json.dumps(arb[value], ensure_ascii=False)};\n'
                              for key, value in keys.items())
            path = ROOT / f"ios/Runner/{native}.lproj/{filename}"
            if check:
                if path.read_text() != output:
                    raise ValueError(f"Stale native localization: {path.relative_to(ROOT)}")
            else:
                path.write_text(output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    generate(parser.parse_args().check)
